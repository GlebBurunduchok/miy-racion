/** Build the static entry point, offline cache and self-contained HTML. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { browserScripts, embeddedAssets, publicFiles, version } from './project.config.mjs';

const base = new URL('./', import.meta.url);
const read = (file) => readFile(new URL(file, base), 'utf8');
const cleanScripts = (html) => html.replace(/\s*<script\b[^>]*\bdefer\b[^>]*>\s*<\/script>/g, '');
const scriptTags = browserScripts
  .map((file) => `  <script defer src="${file}"></script>`)
  .join('\n');
const entry = cleanScripts(await read('index.html')).replace('</head>', scriptTags + '\n</head>');
await writeFile(new URL('index.html', base), entry);

const assets = await Promise.all(
  Object.entries(embeddedAssets).map(async ([file, type]) => {
    const bytes = await readFile(new URL(file, base));
    return [file, `data:${type};base64,${bytes.toString('base64')}`];
  })
);
const inlineAssets = (source) =>
  assets.reduce((text, [file, data]) => text.replaceAll(file, data), source);
let standalone = cleanScripts(entry)
  .replace(/\s*<link\b[^>]*rel="manifest"[^>]*>/, '')
  .replace(/\s*<link\b[^>]*rel="stylesheet"[^>]*>/, '');
standalone = inlineAssets(standalone).replace(
  '</head>',
  `<style>${inlineAssets(await read('styles.css'))}</style></head>`
);
const scripts = await Promise.all(['vendor/zxing-browser.min.js', ...browserScripts].map(read));
standalone = standalone.replace(
  '</body>',
  scripts
    .map(
      (script) => `<script>${inlineAssets(script).replace(/<\/script/gi, '<\\/script')}</script>`
    )
    .join('\n') + '\n</body>'
);
await writeFile(new URL('Mii_Ratsion.html', base), standalone);

const fingerprint = createHash('sha256');
for (const file of publicFiles) fingerprint.update(await readFile(new URL(file, base)));
const cacheName = `mii-ratsion-${version}-${fingerprint.digest('hex').slice(0, 12)}`;
const worker = `// Generated by build-single.mjs. Edit scripts/service-worker.js instead.\nconst CACHE=${JSON.stringify(cacheName)};\nconst FILES=${JSON.stringify(['./', ...publicFiles.map((file) => './' + file)])};\n${await read('scripts/service-worker.js')}`;
await writeFile(new URL('sw.js', base), worker);
console.log(
  `Built Мій раціон ${version}: ${Buffer.byteLength(standalone)} bytes; ${browserScripts.length + 1} embedded scripts.`
);
